export type SeedMovie = {
  tmdbId: number;
  title: string;
  posterPath: string;
  backdropPath?: string;
  overview: string;
  genres: string[];
  runtime?: number;
  releaseYear: number;
  imdbRating?: number;
};

export type SeedCollection = {
  name: string;
  description: string;
  movies: SeedMovie[];
};

function movie(
  tmdbId: number,
  title: string,
  posterPath: string,
  releaseYear: number,
  overview: string,
  genres: string[],
  extras?: Partial<
    Pick<SeedMovie, "runtime" | "imdbRating" | "backdropPath">
  >,
): SeedMovie {
  return {
    tmdbId,
    title,
    posterPath,
    releaseYear,
    overview,
    genres,
    ...extras,
  };
}

