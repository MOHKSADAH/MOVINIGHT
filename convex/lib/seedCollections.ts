export function seedMovieToDoc(m: SeedMovie) {
  return {
    tmdbId: m.tmdbId,
    title: m.title,
    poster: `${TMDB}${m.posterPath}`,
    backdrop: m.backdropPath ? `${BACKDROP}${m.backdropPath}` : undefined,
    overview: m.overview,
    genres: m.genres,
    runtime: m.runtime,
    releaseYear: m.releaseYear,
    imdbRating: m.imdbRating,
  };
}
